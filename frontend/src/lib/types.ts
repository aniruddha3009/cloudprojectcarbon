export type JobClass = "emergency" | "normal" | "background";
export type JobState = "pending" | "queued" | "deferred" | "running" | "paused" | "completed" | "failed" | "cancelled";
export type PolicyName = "fifo" | "threshold" | "debt_reactive" | "debt_predictive";

export interface Decision {
  id: number;
  slot: number;
  sim_time: string;
  job_id: string | null;
  action: string;
  reason: string;
  policy: string;
  controller_state: string;
  intensity: number;
  capacity: number | null;
  details: Record<string, unknown>;
}

export type AppMode = "simulation" | "live";

export interface GridStatus {
  provider: string; region: string; configured: boolean;
  state: "ok" | "stale" | "error" | "waiting" | "not_configured"; polling: boolean;
  intensity: number | null; dominant_fuel: string | null; reading_time: string | null; last_success: string | null;
  last_attempt: string | null; age_seconds: number | null; next_poll: string | null; poll_minutes: number;
  calls_today: number; forecast_points: number; rate_limit: Record<string, string>;
  error: { code: string; message: string; status?: number } | null; notes: string;
}

export interface SystemLoad {
  cpu_percent: number; memory_percent: number; memory_used_gb: number; memory_total_gb: number;
  logical_cpus: number; package_power_w: number | null;
}

export interface ProcessRow {
  pid: number; name: string; cpu_percent: number | null; memory_mb: number | null; status: string | null;
  started_at: string | null; is_app_backend: boolean;
}

export interface EnergyMeterStatus { available: boolean; source: string; message: string }

export interface LiveStatus {
  monitoring: boolean;
  telemetry: {
    refreshed_at: string | null; processes: ProcessRow[]; process_count?: number; system?: SystemLoad; running: boolean;
    interval_s: number; energy_meter: EnergyMeterStatus;
    history: { t: string; cpu_percent: number; memory_percent: number; package_power_w: number | null }[];
  };
  grid: GridStatus;
  managed_workloads: (Job & { cpu_ms_total: number; worker_active: boolean })[];
  slot_seconds: number;
}

export interface SystemState {
  clock: {
    epoch: string; slot: number; sim_time: string; label: string; autoplay: boolean; speed_ms: number;
    scenario_active: boolean; scenario_end_slot: number | null; horizon_slot: number; slot_minutes: number;
  };
  carbon: {
    intensity: number | null; source: string; provider: string; region: string; green: boolean;
    green_threshold: number; debt_threshold: number; mode: "SIMULATED" | "LIVE" | "LIVE_SNAPSHOT"; profile: string;
    /** Simulation only: the presenter-set grid level in force now, if any. */
    manual?: { preset: string; intensity: number; until_slot: number; until_label: string | null } | null;
  };
  ledger: {
    balance_g: number; accrued_g: number; effective_g: number; total_debt_g: number; credits_applied_g: number;
    credits_earned_g: number; peak_effective_g: number; head_hash: string; entries: number;
  };
  totals: { gross_emissions_g: number; energy_kwh: number; deadline_misses: number };
  jobs: { total: number } & Partial<Record<JobState, number>>;
  controller: {
    policy: PolicyName; policy_label: string; state: string; band: number; inversion_active: boolean;
    throttle: Record<string, number>;
  };
  recent_decisions: Decision[];
  mode: AppMode;
  live?: {
    monitoring: boolean; grid: GridStatus; energy_meter: EnergyMeterStatus; system: SystemLoad | null;
    slot_seconds: number; workers: Record<string, number>;
  };
}

export interface Job {
  id: string; name: string; workload: string; job_class: JobClass; priority: number; state: JobState;
  power_w: number; runtime_min: number; energy_estimate_kwh: number;
  arrival_slot: number; arrival_time: string; deadline_slot: number; deadline_time: string;
  start_time: string | null; finish_time: string | null; start_slot: number | null; finish_slot: number | null;
  planned_start_time: string | null; planned_start_slot: number | null; hold_until_time: string | null;
  capacity: number; progress: number; energy_kwh: number; emissions_g: number; debt_g: number; credit_g: number;
  credit_earned_g: number; deferred_by_controller: boolean; baseline_intensity: number | null;
  deadline_missed: boolean; forced: boolean; deferral_count: number; throttle_count: number;
  max_wait_min: number | null; simulate_failure: boolean; last_reason: string | null;
  waiting_min: number | null; delay_min: number | null; manual_run_pending: boolean;
  available_actions: ("run" | "defer" | "cancel")[];
  /** Plain-English status and one-sentence reason, generated by the backend from the last scheduler decision. */
  status_label: string; plain_reason: string; last_action: string | null; decision_intensity: number | null;
}

export interface Execution {
  slot: number; sim_time: string; capacity: number; power_w: number; minutes: number; energy_kwh: number;
  intensity: number; intensity_source: string; emissions_g: number; debt_g: number; energy_source: string;
  kernel_iterations: number | null; kernel_cpu_ms: number | null; kernel_wall_ms: number | null;
  host_power_w: number | null; host_power_source: string | null;
}

export interface LedgerEntry {
  seq: number; event_id: string; event_type: string; job_id: string | null; sim_time: string; recorded_at: string;
  energy_kwh: string | null; intensity_actual: string | null; intensity_baseline: string | null;
  amount_g: string; balance_before_g: string; balance_after_g: string; reference_event_id: string | null;
  idem_key: string; details: Record<string, unknown>; prev_hash: string; hash: string;
}

export type Receipt = Record<string, any>;

export interface JobDetail {
  job: Job;
  decisions: Decision[];
  executions: Execution[];
  ledger: LedgerEntry[];
  receipt: Receipt | null;
}

export interface TimelinePoint {
  slot: number; sim_time: string; intensity: number; source: string; green: boolean; balance_g: number;
  accrued_g: number; effective_debt_g: number; cum_emissions_g: number; cum_debt_g: number; cum_credit_g: number;
  band: number; controller_state: string; running: number; paused: number; queued: number; deferred: number;
  completed: number; throttled: number;
}

export interface CurvePoint { slot: number; sim_time: string; intensity: number; source: string }
export interface Curve {
  provider: string; region: string; profile: string; profile_description: string | null;
  green_threshold: number; debt_threshold: number; current_slot: number; slot_minutes: number; points: CurvePoint[];
}

export interface GanttJob {
  id: string; name: string; job_class: JobClass; state: JobState; arrival_slot: number; deadline_slot: number;
  start_slot: number | null; finish_slot: number | null; planned_start_slot: number | null;
  deferred_by_controller: boolean; segments: { slot: number; capacity: number; intensity: number }[];
}

export interface Placement {
  job_id: string; name: string; job_class: JobClass; priority: number; start_slot: number | null;
  start_time: string | null; window_avg: number | null; now_avg: number; green: boolean; forced: boolean;
  deliberate: boolean; est_savings_g: number; est_debt_g: number; est_credit_g: number; reason: string;
  deadline_time: string;
}

export interface Plan {
  slot: number; sim_time: string; start_debt_g: number; peak_g: number; end_balance_g: number; repayable_g: number;
  projected_new_debt_g: number; horizon_end_slot: number;
  projection: { slot: number; sim_time: string; balance_g: number }[];
  placements: Placement[]; uncertainty_note: string;
}

export interface ControllerSettings {
  policy: PolicyName;
  debt_intensity_threshold: string; green_threshold: string;
  debt_soft_g: string; debt_hard_g: string; debt_critical_g: string;
  workers: number; emergency_reserve: number; static_power_fraction: string;
  min_deferral_savings_g: string; planning_horizon_slots: number; proactive_throttling: boolean;
  carbon_source: "simulated" | "live_snapshot"; profile: string; seed: number; noise_pct: string;
  override: { enabled: boolean; start_hour: number; end_hour: number; intensity: string };
  grid_events: { from_slot: number; to_slot: number; intensity: string; label: string }[];
}

export interface ControllerView {
  settings: ControllerSettings;
  policies: { name: PolicyName; label: string; uses_forecast: boolean; debt_aware: boolean }[];
  profiles: Record<string, string>;
  state: string; band: number; band_names: Record<string, string>;
  throttle_table: Record<string, Record<string, number>>;
  effective_debt_g: number; balance_g: number; current_intensity: number; green_now: boolean;
  plan: Plan; plan_is_advisory: boolean; repayment_queue: Job[]; repaid_jobs: Job[]; active_jobs: Job[];
}

export interface VerifyResult {
  ok: boolean; status: "VERIFIED" | "TAMPERED"; checked: number; head_hash: string; first_bad_seq: number | null;
  problems: string[]; verified_at?: string;
}

export interface ScenarioStep { key: string; title: string; done: boolean; time: string | null; detail: string | null }
export interface ScenarioStatus {
  active: boolean; autoplay: boolean; slot: number; sim_time: string; start_slot: number; end_slot: number;
  steps: ScenarioStep[]; complete: boolean; demo_jobs: { name: string; class: JobClass; story: string }[];
  note?: string | null;
}

export interface WorkloadStat {
  workload: string; jobs: number; completed: number; emissions_g: number; debt_g: number; credit_g: number;
  credit_earned_g: number; net_g: number; deadline_misses: number; deferrals: number; avg_delay_min: number | null;
}

export interface MetricAgg { mean: number; std: number; min: number; max: number }
export interface ExperimentResults {
  reference_policy: PolicyName;
  policies: { name: PolicyName; label: string; uses_forecast: boolean; debt_aware: boolean }[];
  metric_labels: Record<string, { label: string; unit: string }>;
  runs: { policy: PolicyName; seed: number; metrics: Record<string, number> }[];
  aggregates: Record<string, Record<string, MetricAgg>>;
  comparisons_vs_reference_pct: Record<string, Record<string, number | null>>;
  timeseries_seed: number;
  timeseries: Record<string, { slot: number; intensity: number; effective_debt_g: number; cum_emissions_g: number; cum_credit_g: number }[]>;
  sweep: { param: string; policy: PolicyName; points: { value: number; aggregates: Record<string, MetricAgg> }[] } | null;
  trace_summary: { seed: number; jobs: number; by_class: Record<string, number>; estimated_energy_kwh: number };
  environment: Record<string, string>;
  methodology: string[];
}
export interface Experiment {
  id: string; name: string; status: "queued" | "running" | "completed" | "failed"; progress: number;
  config: Record<string, any>; error: string | null; duration_ms: number | null; created_at: string;
  results?: ExperimentResults;
}

export interface TelemetryStatus {
  mode: AppMode;
  simulation: { grid: string; energy: string };
  live: {
    grid: GridStatus;
    energy: { meter_available: boolean; meter_source: string; message: string; method: string };
    processes: string; slot_seconds: number; job_duty: number;
  };
  notes: string[];
}
